// C10 brand check. Run from the repo root: node docs/c10/run.mjs
// Prints a Markdown report to stdout. Rules are in docs/c10/README.md and were fixed before the first run.
import fs from 'node:fs';
import { indexLexicon, matchDescriptors } from '../../engine/matcher.js';
import { oklch, labD50 } from '../../engine/color.js';
import { de00 } from '../../engine/de.js';

const root = new URL('../../', import.meta.url);
const lex = JSON.parse(fs.readFileSync(new URL('data/lexicon.json', root)));
const setPath = process.argv[2] ? new URL(process.argv[2], 'file://' + process.cwd() + '/') : new URL('docs/c10/brand-set.json', root);
const set = JSON.parse(fs.readFileSync(setPath));
const ix = indexLexicon(lex);
const fam = lex.families;
function familyOf(hex) {
  const o = oklch(hex); const c = o.c || 0, h = o.h ?? 0;
  if (c < fam.neutral.C_max) return 'neutral';
  for (const f of fam.families) { const [a, b] = f.h; if (a <= b ? h >= a && h < b : h >= a || h < b) return f.id; }
  return 'red';
}
const hueDiff = (a, b) => { const d = Math.abs((a ?? 0) - (b ?? 0)) % 360; return d > 180 ? 360 - d : d; };
const f2 = (x) => x.toFixed(2), f3 = (x) => x.toFixed(3);

const out = [];
const summary = [];
for (const b of set.brands) {
  out.push(`## ${b.id}\n`);
  for (const [mode, text] of [['verbatim', b.words_verbatim.join(', ')], ...(b.synthesized_terms?.length ? [['synthesized (speculative)', b.synthesized_terms.join(', ')]] : [])]) {
    const r = matchDescriptors(text, ix, { count: 5 });
    const given = mode === 'verbatim' ? b.words_verbatim.length : b.synthesized_terms.length;
    out.push(`### ${mode}\n`);
    out.push(`Input: ${text}  `);
    out.push(`R1 coverage: ${r.matched.length} lexicon terms matched (${r.matched.map((m) => `${m.input} -> ${m.term}`).join('; ') || 'none'}); ${r.unknown.length} unknown words of ${given} given${r.unknown.length ? ` (${r.unknown.join(', ')})` : ''}  `);
    if (!r.seeds.length) { out.push(`R2: no signal (no seeds). Note: ${r.note}\n`); summary.push([b.id, mode, 'no signal', `${r.matched.length}/${given}`]); continue; }
    out.push(`Seeds: ${r.seeds.map((s) => `${s.hex} ${s.family} (L ${s.oklch.l}, C ${s.oklch.c}, h ${s.oklch.h}; score ${s.score}${s.beyondTested ? `; beyond tested range, ${s.beyondTested.side}` : ""})`).join(' | ')}  `);
    if (r.note) out.push(`Matcher note: ${r.note}  `);
    const seedFams = new Set(r.seeds.map((s) => s.family));
    const targets = b.colors.filter((c) => !['#000000', '#ffffff'].includes(c.hex.toLowerCase()));
    const r2 = targets.map((c) => ({ c, fam: familyOf(c.hex), hit: seedFams.has(familyOf(c.hex)) }));
    const pass = r2.some((x) => x.hit);
    out.push(`R2 hue family: ${pass ? 'PASS' : 'FAIL'} (brand ${r2.map((x) => `${x.c.hex} ${x.fam}${x.hit ? ' found' : ' not found'}`).join(', ')}; seed families ${[...seedFams].join(', ')})  `);
    const r3 = targets.map((c) => {
      const lc = labD50(c.hex), oc = oklch(c.hex);
      let best = null;
      for (const s of r.seeds) { const d = de00(lc, labD50(s.hex)); if (!best || d < best.d) best = { d, s }; }
      const os = oklch(best.s.hex);
      return `${c.hex} nearest ${best.s.hex}: dE00 ${f2(best.d)}, dL ${f2(os.l - oc.l)}, dC ${f3((os.c || 0) - (oc.c || 0))}, dh ${Math.round(hueDiff(os.h, oc.h))}°`;
    });
    out.push(`R3 closeness: ${r3.join('; ')}\n`);
    summary.push([b.id, mode, pass ? 'PASS' : 'FAIL', `${r.matched.length}/${given}`]);
  }
}
console.log('# C10 run output\n');
console.log(`Generated by docs/c10/run.mjs from data/lexicon.json (${lex.version}). Do not edit by hand.\n`);
console.log('| Brand | Run | R2 | R1 matched/given |\n| --- | --- | --- | --- |');
for (const s of summary) console.log(`| ${s.join(' | ')} |`);
console.log('\n' + out.join('\n'));
