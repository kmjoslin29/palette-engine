// Palette Engine — CSS custom properties. Light values on :root; dark values under prefers-color-scheme (unless the page pins
// data-theme="light") and under [data-theme="dark"]. OKLCH is given as a comment beside each hex.

import { TONES, ROLES } from '../palette.js';
import { oklch, roundOklch } from '../color.js';
import { PALETTE_KEYS, assertExportable, oklchText, byRegion } from './model.js';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const ok = (hex) => oklchText(roundOklch(oklch(hex)));
const safeComment = (s) => String(s).replace(/\*\//g, '* /').replace(/[\r\n]+/g, ' ');

export const roleVar = (role) => `--color-role-${kebab(role)}`;
export const toneVar = (name, tone) => `--color-${name}-${tone}`;
export const brandVar = (slot) => `--color-brand-${slot}`;

export function cssVariables(model) {
  assertExportable(model);
  const pal = model.palette;
  const line = (indent, name, hex) => `${indent}${name}: ${hex};  /* ${ok(hex)} */`;
  const roles = (mode, indent) => ROLES.map((r) => line(indent, roleVar(r), pal.schemes[mode][r]));
  const out = [];
  out.push('/* Color tokens for ' + safeComment(model.name) + '. Generated by Palette Engine on ' + model.date + '. */');
  out.push('/* Print: ' + byRegion(model.conditions.profiles) + ', ' + model.conditions.intent + '. Swatches are not proofs. */');
  out.push('/* Roles: ' + model.conditions.roleModel + '. Dark roles apply under prefers-color-scheme: dark unless data-theme="light" is set, or whenever data-theme="dark" is set. */');
  out.push('', ':root {', '  color-scheme: light;', '', '  /* Brand colors (your own hex, kept exactly) */');
  for (const c of model.colors) out.push(line('  ', brandVar(c.slot), c.hex).replace(/\/\*/, `/* ${safeComment(c.name)}: `));
  out.push('');
  for (const [key, name] of Object.entries(PALETTE_KEYS)) {
    out.push(`  /* Tonal palette: ${name} */`);
    for (const t of TONES) out.push(line('  ', toneVar(name, t), pal.tones[key][t]));
    out.push('');
  }
  out.push('  /* Roles: light */', ...roles('light', '  '), '}', '');
  out.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', '    color-scheme: dark;', ...roles('dark', '    '), '  }', '}', '');
  out.push(':root[data-theme="dark"] {', '  color-scheme: dark;', ...roles('dark', '  '), '}', '');
  return out.join('\n');
}
