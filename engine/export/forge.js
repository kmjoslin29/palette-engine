// Palette Engine — Forge Tokens JSON (default) and DTCG 2025.10 (second file).
// Forge shape (from Design System Forge's exporter): root { $description, $version, color: { <palette>: { <tone>: { $value: hex, $type: 'color' } } },
// $themes: [light -> group "color", dark -> group "color-dark"], "color-dark": {...} }. Forge writes CMYK under a bare $extensions.cmyk;
// Palette Engine writes print and spot data under $extensions.com.kwadejoslin.palette instead (namespaced, per DTCG's vendor-key rule).
// DTCG 2025.10 has no $version and no theming (the resolver module covers modes), so that file drops $version and $themes.

import { TONES, ROLES } from '../palette.js';
import { NS, PALETTE_KEYS, assertExportable, colorRecord, pairLabel } from './model.js';

const hexBytes = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));

/** DTCG 2025.10 color value: colorSpace, components (0..1), hex fallback. */
export const dtcgColor = (hex) => ({ colorSpace: 'srgb', components: hexBytes(hex).map((v) => v / 255), alpha: 1, hex: hex.toLowerCase() });
export const hexValue = (hex) => hex.toLowerCase();

const compactPrint = (pr) => (pr ? Object.fromEntries(Object.entries(pr).map(([id, r]) => [id, { cmyk: r.cmyk, tac: r.tac, inGamut: r.inGamut }])) : null);

function rootExtension(model) {
  return {
    generator: `${model.generator.name} (phase ${model.generator.phase})`, date: model.date, name: model.name,
    conditions: { intent: model.conditions.intent, profiles: model.conditions.profiles.map((p) => ({ id: p.id, label: p.label, region: p.region, tacLimit: p.tacLimit, profileSha256: p.sha256 })), printAvailable: model.conditions.printAvailable, roleModel: model.conditions.roleModel, wheel: model.conditions.wheel },
    statements: ['Print swatches are lookup-table approximations, not proofs.', 'Spot names are approximate and come from values the designer pasted; verify against a current physical guide under D50 light.'],
    acceptedFailures: model.accepted.map((f) => ({ mode: f.mode, pair: pairLabel(f), ratio: f.ratio, required: f.required, note: f.note })),
    earlierAcceptedNotes: model.acceptedStale.map((f) => ({ mode: f.mode, pair: pairLabel(f), note: f.note })),
    roleOverrides: model.overrides,
  };
}

/** Shared tree: the same groups in both formats; only the value shape differs. */
function tree(model, toValue) {
  const pal = model.palette;
  const color = {};
  for (const [key, name] of Object.entries(PALETTE_KEYS)) {
    color[name] = {};
    for (const t of TONES) {
      const hex = pal.tones[key][t];
      const tok = { $value: toValue(hex), $type: 'color' };
      const pr = compactPrint(model.printOf(hex));
      if (pr) tok.$extensions = { [NS]: { print: pr } };
      color[name][String(t)] = tok;
    }
  }
  color.brand = {};
  for (const c of model.colors) color.brand[c.slot] = { $value: toValue(c.hex), $type: 'color', $description: c.name, $extensions: { [NS]: colorRecord(c, model) } };
  const roles = (mode) => Object.fromEntries(ROLES.map((r) => [r, { $value: toValue(pal.schemes[mode][r]), $type: 'color' }]));
  color.role = roles('light');
  return { color, colorDark: { role: roles('dark') } };
}

/** Forge Tokens JSON (default format). */
export function forgeTokens(model) {
  assertExportable(model);
  const { color, colorDark } = tree(model, hexValue);
  return {
    $description: `Color tokens for ${model.name}. Generated by Palette Engine`,
    $version: '1.0.0',
    color,
    $themes: [{ name: 'light', group: 'color', description: 'Default light theme' }, { name: 'dark', group: 'color-dark', description: 'Dark theme roles' }],
    'color-dark': colorDark,
    $extensions: { [NS]: rootExtension(model) },
  };
}

/** DTCG 2025.10 (second file). */
export function dtcgTokens(model) {
  assertExportable(model);
  const { color, colorDark } = tree(model, dtcgColor);
  return {
    $description: `Color tokens for ${model.name}. Generated by Palette Engine. Light roles are in "color"; dark roles are in "color-dark" (DTCG 2025.10 defines modes in its resolver module, not in the format).`,
    color,
    'color-dark': colorDark,
    $extensions: { [NS]: rootExtension(model) },
  };
}

export const forgeTokensJson = (model) => JSON.stringify(forgeTokens(model), null, 2) + '\n';
export const dtcgTokensJson = (model) => JSON.stringify(dtcgTokens(model), null, 2) + '\n';
